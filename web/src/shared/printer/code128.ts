// Штрихкод Code128 — им службы доставки кодируют номер отправления, его пикают в ПВЗ.
// Цифры парами кодируем набором C (вдвое короче), остальное — набором B. Без библиотек: таблица ниже — стандарт.

/** Ширины полос и пробелов для значений 0–106 (106 — стоп, у него 7 элементов). */
