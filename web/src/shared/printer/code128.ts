const START_B = 104;
const START_C = 105;
const CODE_B = 100;
const CODE_C = 99;
const STOP = 106;

const isDigit = (ch: string) => ch >= "0" && ch <= "9";

/** Сколько цифр подряд, начиная с i. */
function digitRun(text: string, i: number) {
  let n = 0;
  while (i + n < text.length && isDigit(text[i + n])) n++;
  return n;
}

/** Значения символов с контрольной суммой и стопом. Только печатные ASCII (номера отправлений такие). */
function encode(text: string): number[] {
  const values: number[] = [];
  // Набор C выгоден, если цифр подряд хотя бы 4 (или весь текст — 2+ цифры).
  const wantC = (i: number) => {
    const run = digitRun(text, i);
    return run >= 4 || (run >= 2 && run === text.length - i && i === 0);
  };
  let set: "B" | "C" = wantC(0) ? "C" : "B";
  values.push(set === "C" ? START_C : START_B);

  let i = 0;
  while (i < text.length) {
    if (set === "B" && wantC(i)) {
      // Нечётное число цифр: одну оставляем в B, остальные парами в C.
      if (digitRun(text, i) % 2 === 1) {
        values.push(text.charCodeAt(i) - 32);
        i++;
      }
      values.push(CODE_C);
      set = "C";
      continue;
    }
    if (set === "C") {
      if (digitRun(text, i) >= 2) {
        values.push(Number(text.slice(i, i + 2)));
        i += 2;
        continue;
      }
      values.push(CODE_B);
      set = "B";
      continue;
    }
    const code = text.charCodeAt(i);
    if (code < 32 || code > 126) throw new Error(`Code128: символ «${text[i]}» не поддерживается`);
    values.push(code - 32);
    i++;
  }

  const check = values.reduce((sum, v, idx) => sum + v * (idx === 0 ? 1 : idx), 0) % 103;
  values.push(check, STOP);
  return values;
}

/** Полосы штрихкода в модулях: чётные элементы — чёрные, нечётные — белые. Без белых полей. */
export function code128Bars(text: string): number[] {
  return encode(text).flatMap((v) => [...PATTERNS[v]].map(Number));
}

/** Ширина штрихкода в модулях (без белых полей). */
export const code128Width = (bars: number[]) => bars.reduce((a, b) => a + b, 0);
