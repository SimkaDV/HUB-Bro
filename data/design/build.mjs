#!/usr/bin/env node
// Builds both apps' themes from data/design/tokens.json (no dependencies):
//   hub-bro/web/src/shared/styles/tokens.css  — CSS custom properties for HUB BRO
//   bot/manager-app/ui_theme.py               — Flet theme for the bot's manager app
// Usage: node data/design/build.mjs [--check]   (--check: only report whether the outputs are up to date)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const T = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));

const CSS_OUT = join(root, "hub-bro/web/src/shared/styles/tokens.css");
const PY_OUT = join(root, "bot/manager-app/ui_theme.py");

// ---------- helpers ----------
const entries = (group) =>
  Object.entries(group ?? {})
    .filter(([k]) => !k.startsWith("$"))
    .map(([k, v]) => (v !== null && typeof v === "object" ? [k, v.value, v.comment] : [k, v, undefined]));
const val = (group, name) => entries(group).find(([k]) => k === name)?.[1];
const px = (s) => parseInt(String(s), 10);
const hex6 = (h) => {
  const m = /^#([0-9a-f]{3})$/i.exec(h);
  return (m ? "#" + [...m[1]].map((c) => c + c).join("") : h).toLowerCase();
};

const C = T.color;
const font = T.typography.font;
const fontStack = [`"${font.family}"`, ...font.fallbacks].join(", ");

// ---------- tokens.css ----------
function buildCss() {
  const lines = [];
  const block = (group, header) => {
    if (header) lines.push(`  /* ${header} */`);
    for (const [k, v, comment] of entries(group)) {
      if (comment) lines.push(`  /* ${comment} */`);
      lines.push(`  --${k}: ${v};`);
    }
    lines.push("");
  };
  lines.push("/* generated by data/design/build.mjs from data/design/tokens.json — do not edit */");
  lines.push("/* Дизайн-токены HUB BRO. Описание — docs/DESIGN.md */");
  lines.push(":root {");
  // surface + text + accent form one block, like the original file
  for (const g of [C.surface, C.text, C.accent]) {
    for (const [k, v, comment] of entries(g)) {
      if (comment) lines.push(`  /* ${comment} */`);
      lines.push(`  --${k}: ${v};`);
    }
  }
  lines.push("");
  block(C.status);
  block(C.stock);
  lines.push(`  --font: ${fontStack};`, "");
  for (const [k, v] of entries(T.radius)) lines.push(`  --${k}: ${v};`);
  lines.push(`  --control-height: ${val(T.size, "control-height")};`, "");
  block(T.space);
  lines.push(`  --sidebar-width: ${val(T.size, "sidebar-width")};`, "");
  for (const [k, v] of entries(T.motion)) lines.push(`  --${k}: ${v};`);
  lines.push("}", "");
  return lines.join("\n");
}

// ---------- ui_theme.py ----------
function buildPy() {
  const c = (group, name) => hex6(val(group, name));
  const P = {
    bg: c(C.surface, "bg"),
    card: c(C.surface, "card"),
    paper: c(C.surface, "paper"),
    text: c(C.text, "text"),
    text2: c(C.text, "text-secondary"),
    button: c(C.accent, "button"),
    on_button: c(C.accent, "on-button"),
  };
  const st = Object.fromEntries(entries(C.status).map(([k, v]) => [k, hex6(v)]));
  const stock = Object.fromEntries(entries(C.stock).map(([k, v]) => [k.replace("stock-", ""), hex6(v)]));
  const sp = Object.fromEntries(entries(T.space).map(([k, v]) => [k.replace("space-", ""), px(v)]));
  const size = T.typography.size;
  const w = (n) => `ft.FontWeight.W_${n}`;
  const W = T.typography.weight;
  const pyDict = (o, indent = 4) =>
    "dict(" + Object.entries(o).map(([k, v]) => `${k}=${typeof v === "string" ? JSON.stringify(v) : v}`).join(", ") + ")";
  const pyMap = (o) => "{" + Object.entries(o).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(", ") + "}";

  // Old palette keys kept so nothing that read ui_theme.LIGHT breaks; values now come from the hub.
  const light = {
    bg: P.bg, surface: P.card, surface2: P.bg, border: P.card, border_strong: P.text2,
    text: P.text, text2: P.text2, text3: P.text2, accent: P.button, accent_ink: P.text,
    bad: st["danger-text"], good: st["success-text"], warn: st["warning-text"], on_color: P.on_button,
    card: P.card, paper: P.paper, neutral: st["neutral-bg"],
  };
  const tones = ["danger", "success", "warning", "neutral"];
  const status = Object.fromEntries(tones.map((t) => [t, { bg: st[`${t}-bg`], text: st[`${t}-text`] }]));

  return `"""generated by data/design/build.mjs from data/design/tokens.json — do not edit (change tokens.json, rerun the build).

Look of the manager app = HUB BRO's design (hub-bro/docs/DESIGN.md): light only (the hub has no dark theme), warm
grey-beige background, darker beige cards without borders or shadows, black buttons with white text, Onest font,
${px(val(T.radius, "radius-card"))}px cards, ${px(val(T.radius, "radius-button"))}px buttons and inputs, muted status tones. Code uses the Material roles below, never fixed colors:
  PRIMARY = black (buttons, selection), ON_SURFACE_VARIANT = secondary text,
  TERTIARY = success (green), SECONDARY = warning (amber), ERROR = danger (red),
  *_CONTAINER = the matching status background, SURFACE_CONTAINER_LOWEST = card, SURFACE_CONTAINER_HIGH = field/box on a card."""
import flet as ft

SANS = ${JSON.stringify(font.family)}
SANS_URL = ${JSON.stringify(font.fletFontUrl)}  # same Google Fonts family the hub loads (${font.webCssUrl})
MONO = ${JSON.stringify(T.typography.mono.family)}  # manager app only: template editor, size grid
RADIUS = ${px(val(T.radius, "radius-card"))}          # cards, dialogs (--radius-card)
RADIUS_SMALL = ${px(val(T.radius, "radius-button"))}    # buttons, chips, inputs (--radius-button)
RADIUS_PILL = ${T.radiusExtra.pill}
CONTROL_HEIGHT = ${px(val(T.size, "control-height"))}
SPACE = ${pyMap(sp).replace(/"(\d+)"/g, "$1")}  # --space-N

LIGHT = ${pyDict(light)}
DARK = LIGHT  # the hub has no dark theme; kept as an alias for old imports, the app runs ThemeMode.LIGHT

# Status tones (badge background + text), stock digits on black chips, and which tone each hub status uses.
STATUS = ${JSON.stringify(status).replace(/"(\w+)":/g, '"$1": ').replace(/,"/g, ', "')}
STOCK = ${pyMap(stock)}
STOCK_LOW, STOCK_MID = ${T.stockLevels.low}, ${T.stockLevels.mid}
ORDER_STATUS_TONE = ${pyMap(T.statusTone.order)}
UNIT_STATUS_TONE = ${pyMap(T.statusTone.unit)}


def stock_color(count):
    """Digit color for a stock count on a black chip (0 → grey, struck through in the hub)."""
    return STOCK["zero"] if count <= 0 else STOCK["low"] if count <= STOCK_LOW else STOCK["mid"] if count <= STOCK_MID else STOCK["ok"]


def _theme(c):
    text = lambda size=${size.body}, weight=${w(W.regular)}, color=None: ft.TextStyle(font_family=SANS, size=size, weight=weight,
                                                                              color=color)
    button = lambda **kw: ft.ButtonStyle(text_style=text(${size.control}, ${w(W.regular)}),
                                         shape=ft.RoundedRectangleBorder(radius=RADIUS_SMALL),
                                         padding=ft.Padding.symmetric(horizontal=SPACE[4], vertical=SPACE[3]), elevation=0, **kw)
    return ft.Theme(
        font_family=SANS,
        use_material3=True,
        scaffold_bgcolor=c["bg"],
        color_scheme=ft.ColorScheme(
            primary=c["accent"], on_primary=c["on_color"],
            primary_container=c["card"], on_primary_container=c["text"],
            secondary=${JSON.stringify(st["warning-text"])}, on_secondary=c["on_color"],
            # Material uses secondary_container for selection (nav indicator, chips): black like the hub's active items
            secondary_container=c["accent"], on_secondary_container=c["on_color"],
            tertiary=${JSON.stringify(st["success-text"])}, on_tertiary=c["on_color"],
            tertiary_container=${JSON.stringify(st["success-bg"])}, on_tertiary_container=${JSON.stringify(st["success-text"])},
            error=${JSON.stringify(st["danger-text"])}, on_error=c["on_color"],
            error_container=${JSON.stringify(st["danger-bg"])}, on_error_container=${JSON.stringify(st["danger-text"])},
            surface=c["bg"], on_surface=c["text"], on_surface_variant=c["text2"],
            surface_container_lowest=c["card"], surface_container_low=c["card"],
            surface_container=c["card"], surface_container_high=c["bg"],
            surface_container_highest=c["neutral"], surface_tint=ft.Colors.TRANSPARENT,
            outline=c["border_strong"], outline_variant=c["border"],
            inverse_surface=c["text"], on_inverse_surface=c["bg"], inverse_primary=c["bg"]),
        text_theme=ft.TextTheme(body_small=text(${size.hint}, color=c["text"]),
                                body_medium=text(${size.body}, color=c["text"]),
                                body_large=text(${size.control}, color=c["text"])),
        filled_button_theme=ft.FilledButtonTheme(style=button(bgcolor=c["accent"], color=c["on_color"])),
        # ft.Button = the hub's secondary button; neutral-bg so it shows on both the page and a card
        button_theme=ft.ButtonTheme(style=button(bgcolor=c["neutral"], color=c["text"])),
        outlined_button_theme=ft.OutlinedButtonTheme(style=button(color=c["text"], side=ft.BorderSide(1, c["border_strong"]))),
        text_button_theme=ft.TextButtonTheme(style=button(color=c["text"])),
        navigation_rail_theme=ft.NavigationRailTheme(
            bgcolor=c["bg"], indicator_color=c["accent"],
            indicator_shape=ft.RoundedRectangleBorder(radius=RADIUS_SMALL),
            selected_label_text_style=text(${size.hint}, ${w(W.semibold)}, c["text"]),
            unselected_label_text_style=text(${size.hint}, ${w(W.regular)}, c["text2"])),
        list_tile_theme=ft.ListTileTheme(selected_tile_color=c["accent"], selected_color=c["on_color"],
                                         shape=ft.RoundedRectangleBorder(radius=RADIUS_SMALL)),
        dialog_theme=ft.DialogTheme(bgcolor=c["bg"], shape=ft.RoundedRectangleBorder(radius=RADIUS)),
        snackbar_theme=ft.SnackBarTheme(bgcolor=c["text"], content_text_style=text(${size.body}, color=c["bg"]),
                                        shape=ft.RoundedRectangleBorder(radius=RADIUS_SMALL)),
        divider_theme=ft.DividerTheme(color=c["bg"], thickness=1),
        input_decoration_theme=ft.InputDecorationTheme(filled=True, fill_color=c["bg"],
                                                       hint_style=ft.TextStyle(color=c["text2"])),
    )


def apply(page: ft.Page):
    page.fonts = {**(page.fonts or {}), SANS: SANS_URL}
    page.theme_mode = ft.ThemeMode.LIGHT
    page.theme = _theme(LIGHT)
    page.dark_theme = page.theme


def eyebrow(text):
    """Small label above a page title (secondary text, like the hub's subtitles and hints)."""
    return ft.Text(text, font_family=SANS, size=${size.hint}, weight=${w(W.medium)}, color=ft.Colors.ON_SURFACE_VARIANT)


def page_title(text, label="BOT BRO"):
    """Page header: eyebrow + ${size["page-title"]}px semibold title, like the hub's PageHeader."""
    return ft.Column([eyebrow(label), ft.Text(text, size=${size["page-title"]}, weight=${w(W.semibold)})], spacing=${sp[1]})


def hint(text, **kw):
    """Muted small text (the hub's .hint: ${size.hint}px, --text-secondary)."""
    return ft.Text(text, font_family=SANS, size=${size.hint}, color=kw.pop("color", ft.Colors.ON_SURFACE_VARIANT), **kw)
`;
}

// ---------- write ----------
const outputs = [
  [CSS_OUT, buildCss()],
  [PY_OUT, buildPy()],
];
const check = process.argv.includes("--check");
let stale = 0;
for (const [file, content] of outputs) {
  const rel = relative(root, file);
  let current = null;
  try { current = readFileSync(file, "utf8"); } catch {}
  if (current === content) { console.log(`up to date  ${rel}`); continue; }
  if (check) { console.log(`STALE       ${rel}`); stale++; continue; }
  writeFileSync(file, content);
  console.log(`written     ${rel}`);
}
if (stale) process.exit(1);
